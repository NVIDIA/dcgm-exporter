func TestCollectComponentsExcludesNVIDIAFirstPartyModules(t *testing.T) {
	moduleDirectory := t.TempDir()
	configureFakeGo(t, moduleDirectory)
	t.Setenv("FAKE_GO_LICENSE_PATH", filepath.Join(moduleDirectory, "LICENSE"))
	listOutput := filepath.Join(t.TempDir(), "list.json")
	t.Setenv("FAKE_GO_LIST_OUTPUT", listOutput)
	metadata := fmt.Sprintf(
		"{\"Module\":{\"Path\":\"github.com/NVIDIA/go-dcgm\",\"Version\":\"v1.0.0\",\"Dir\":%q}}\n"+
			"{\"Module\":{\"Path\":\"github.com/NVIDIA/go-nvml\",\"Version\":\"v1.0.0\",\"Dir\":%q}}\n"+
			"{\"Module\":{\"Path\":\"example.com/dependency\",\"Version\":\"v1.0.0\",\"Dir\":%q}}\n",
		filepath.Join(t.TempDir(), "go-dcgm"), filepath.Join(t.TempDir(), "go-nvml"), moduleDirectory)
	if err := os.WriteFile(listOutput, []byte(metadata), 0o600); err != nil {
		t.Fatalf("write fake module list: %v", err)
	}

	components, err := collectComponents("./cmd/dcgm-exporter", []target{{GOOS: "linux", GOARCH: "amd64"}})
	if err != nil {
		t.Fatalf("collect components: %v", err)
	}
	if got, want := len(components), 1; got != want {
		t.Fatalf("component count = %d, want %d", got, want)
	}
	if got, want := components[0].Path, "example.com/dependency"; got != want {
		t.Errorf("component path = %q, want %q", got, want)
	}
}

func TestCollectComponentsStopsOnModuleVerificationFailure(t *testing.T) {
	moduleDirectory := t.TempDir()
	commandLog := configureFakeGo(t, moduleDirectory)
	t.Setenv("FAKE_GO_VERIFY_ERROR", "example.com/dependency@v1.0.0: checksum mismatch")

	_, err := collectComponents("./cmd/dcgm-exporter", []target{{GOOS: "linux", GOARCH: "amd64"}})
	if err == nil {
		t.Fatal("collectComponents accepted a module-cache verification failure")
	}
	if !strings.Contains(err.Error(), "verify module cache") || !strings.Contains(err.Error(), "checksum mismatch") {
		t.Fatalf("verification error = %q, want command context and command output", err)
	}

	assertCommandLog(t, commandLog, "list -buildvcs=false -deps -json ./cmd/dcgm-exporter\nmod verify\n")
}

func configureFakeGo(t *testing.T, moduleDirectory string) string {
	t.Helper()

	binDirectory := t.TempDir()
	goPath := filepath.Join(binDirectory, "go")
	program := `#!/bin/sh
set -eu
printf '%s\n' "$*" >> "${FAKE_GO_LOG}"
if [ "${GOWORK:-}" != "off" ]; then
	printf 'unexpected GOWORK=%s\n' "${GOWORK:-}" >&2
	exit 40
fi
if [ "$1" = "list" ]; then
	cat "${FAKE_GO_LIST_OUTPUT}"
	exit 0
fi
if [ "$1" = "mod" ] && [ "$2" = "verify" ]; then
	if [ -n "${FAKE_GO_VERIFY_ERROR:-}" ]; then
		printf '%s\n' "${FAKE_GO_VERIFY_ERROR}" >&2
		exit 41
	fi
	if [ -n "${FAKE_GO_LICENSE_PATH:-}" ]; then
		printf 'test license\n' > "${FAKE_GO_LICENSE_PATH}"
	fi
	printf 'all modules verified\n'
	exit 0
fi
printf 'unexpected go command: %s\n' "$*" >&2
exit 42
`
	// #nosec G306 -- the private test helper must be executable.
	if err := os.WriteFile(goPath, []byte(program), 0o700); err != nil {
		t.Fatalf("write fake go executable: %v", err)
	}

	listOutput := filepath.Join(t.TempDir(), "list.json")
	metadata := fmt.Sprintf("{\"Module\":{\"Path\":\"example.com/dependency\",\"Version\":\"v1.0.0\",\"Dir\":%q}}\n", moduleDirectory)
	if err := os.WriteFile(listOutput, []byte(metadata), 0o600); err != nil {
		t.Fatalf("write fake go list output: %v", err)
	}

	commandLog := filepath.Join(t.TempDir(), "commands.log")
	t.Setenv("PATH", binDirectory+string(os.PathListSeparator)+os.Getenv("PATH"))
	t.Setenv("FAKE_GO_LOG", commandLog)
	t.Setenv("FAKE_GO_LIST_OUTPUT", listOutput)
	return commandLog
}

func assertCommandLog(t *testing.T, path, want string) {
	t.Helper()

	contents, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read fake go command log: %v", err)
	}
	if got := string(contents); got != want {
		t.Errorf("go command log = %q, want %q", got, want)
	}
}

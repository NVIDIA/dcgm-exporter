func TestParseTargets(t *testing.T) {
	t.Parallel()

	targets, err := parseTargets("linux/arm64, linux/amd64,linux/arm64")
	if err != nil {
		t.Fatalf("parse targets: %v", err)
	}

	got := targetNames(targets)
	want := []string{"linux/amd64", "linux/arm64"}
	if len(got) != len(want) {
		t.Fatalf("target count = %d, want %d", len(got), len(want))
	}
	for index := range want {
		if got[index] != want[index] {
			t.Errorf("target %d = %q, want %q", index, got[index], want[index])
		}
	}
}

func TestParseTargetsRejectsInvalidValue(t *testing.T) {
	t.Parallel()

	if _, err := parseTargets("linux"); err == nil {
		t.Fatal("parseTargets accepted a target without an architecture")
	}
}

func TestIsLegalFileName(t *testing.T) {
	t.Parallel()

	for _, test := range []struct {
		name string
		want bool
	}{
		{name: "LICENSE", want: true},
		{name: "LICENCE.md", want: true},
		{name: "LICENSE-APACHE", want: true},
		{name: "NOTICE.txt", want: true},
		{name: "COPYING", want: true},
		{name: "README.md", want: false},
		{name: "licenses.md", want: false},
	} {
		test := test
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			if got := isLegalFileName(test.name); got != test.want {
				t.Errorf("isLegalFileName(%q) = %t, want %t", test.name, got, test.want)
			}
		})
	}
}

func TestReadNoticeFilesUsesSortedTopLevelLegalFiles(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	for name, contents := range map[string]string{
		"LICENSE-Z": "license z",
		"NOTICE":    "notice",
		"README.md": "not legal material",
	} {
		if err := os.WriteFile(filepath.Join(directory, name), []byte(contents), 0o600); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}

	files, err := readNoticeFiles(directory)
	if err != nil {
		t.Fatalf("read notice files: %v", err)
	}
	if got, want := len(files), 2; got != want {
		t.Fatalf("notice file count = %d, want %d", got, want)
	}
	if got, want := files[0].Name, "LICENSE-Z"; got != want {
		t.Errorf("first notice file = %q, want %q", got, want)
	}
	if got, want := files[1].Name, "NOTICE"; got != want {
		t.Errorf("second notice file = %q, want %q", got, want)
	}
}

func TestReadNoticeFilesRejectsBlankLegalFile(t *testing.T) {
	t.Parallel()

	directory := t.TempDir()
	if err := os.WriteFile(filepath.Join(directory, "LICENSE"), []byte(" \t\r\n\n"), 0o600); err != nil {
		t.Fatalf("write blank legal file: %v", err)
	}

	_, err := readNoticeFiles(directory)
	if err == nil || !strings.Contains(err.Error(), "LICENSE is empty") {
		t.Fatalf("read notice files error = %v, want blank-file failure", err)
	}
}

func TestRenderNoticesContract(t *testing.T) {
	t.Parallel()

	got := string(renderNotices(
		"./cmd/example",
		[]target{{GOOS: "linux", GOARCH: "amd64"}, {GOOS: "linux", GOARCH: "arm64"}},
		[]component{{
			Path:    "example.com/dependency",
			Version: "v1.2.3",
			NoticeFiles: []noticeFile{
				{Name: "LICENSE", Text: []byte("license text\n")},
				{Name: "NOTICE", Text: []byte("notice text")},
			},
		}},
	))
	want := `THIRD-PARTY NOTICES FOR THE DCGM-EXPORTER BINARY

This generated file contains the legal materials supplied by third-party Go modules compiled into the production dcgm-exporter binary for the targets below.
It is intended to ship beside the project LICENSE in standalone binary distributions.
Runtime libraries supplied by the host are not part of that binary payload and are outside this file's scope.
Container images combine this file with the legal materials for every additional component they ship. Do not edit this file manually.
Package: ./cmd/example
Targets: linux/amd64, linux/arm64
Scope: third-party Go code compiled into the production dcgm-exporter binary.
NVIDIA-authored modules are excluded from this third-party notice bundle.
Excluded: dynamically supplied host libraries and other files not contained in the standalone binary payload.

================================================================================
Module: example.com/dependency
Version: v1.2.3
File: LICENSE
File: NOTICE
================================================================================

--- LICENSE ---

license text

--- NOTICE ---

notice text
`
	if got != want {
		t.Errorf("rendered notices mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}


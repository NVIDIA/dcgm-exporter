func TestListModulesDisablesWorkspaceOverrides(t *testing.T) {
	moduleDirectory := t.TempDir()
	commandLog := configureFakeGo(t, moduleDirectory)
	t.Setenv("GOWORK", filepath.Join(t.TempDir(), "injected.go.work"))

	modules, err := listModules("./cmd/dcgm-exporter", target{GOOS: "linux", GOARCH: "amd64"})
	if err != nil {
		t.Fatalf("list modules: %v", err)
	}
	if got, want := len(modules), 1; got != want {
		t.Fatalf("module count = %d, want %d", got, want)
	}
	if got, want := modules[0].key(), "example.com/dependency@v1.0.0"; got != want {
		t.Errorf("module key = %q, want %q", got, want)
	}

	assertCommandLog(t, commandLog, "list -buildvcs=false -deps -json ./cmd/dcgm-exporter\n")
}


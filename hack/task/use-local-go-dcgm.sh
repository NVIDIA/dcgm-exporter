# Select one validated local go-dcgm checkout for Go and Bazel without overwriting unrelated local configuration.

set -euo pipefail

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
go_dcgm_dir="${GO_DCGM_DIR:-}"
go_dcgm_module="github.com/NVIDIA/go-dcgm"
go_command="${GO:-go}"
go_workfile="${root_dir}/go.work"
bazel_local_config="${root_dir}/.bazelrc.local"
generated_config_header='# Generated by task dev:go-dcgm:use. Delete this file to use the pinned go-dcgm module.'

if [[ -z "${go_dcgm_dir}" ]]; then
    echo "ERROR: set GO_DCGM_DIR to the local go-dcgm checkout you want to use" >&2
    exit 2
fi
if [[ ! -d "${go_dcgm_dir}" ]]; then
    echo "ERROR: GO_DCGM_DIR is not a directory: ${go_dcgm_dir}" >&2
    exit 2
fi

source_dir="$(cd "${go_dcgm_dir}" && pwd -P)"
if [[ "${source_dir}" == *[[:space:]]* ]]; then
    echo "ERROR: GO_DCGM_DIR must not contain whitespace for Bazel's local configuration: ${source_dir}" >&2
    exit 2
fi

module="$(GOWORK=off "${go_command}" -C "${source_dir}" list -m -f '{{.Path}}')"
if [[ "${module}" != "${go_dcgm_module}" ]]; then
    echo "ERROR: expected ${go_dcgm_module} at ${source_dir}, got ${module}" >&2
    exit 1
fi
if [[ ! -f "${source_dir}/MODULE.bazel" ]] || \
    ! grep -Eq '^[[:space:]]*module[[:space:]]*\([[:space:]]*name[[:space:]]*=[[:space:]]*"go_dcgm"' "${source_dir}/MODULE.bazel"; then
    echo "ERROR: expected Bazel module go_dcgm at ${source_dir}/MODULE.bazel" >&2
    exit 1
fi

if { [[ -e "${bazel_local_config}" || -L "${bazel_local_config}" ]]; } && {
    [[ -L "${bazel_local_config}" || ! -f "${bazel_local_config}" || \
        "$(wc -l <"${bazel_local_config}")" -ne 2 ]] || \
        ! grep -Fqx "${generated_config_header}" "${bazel_local_config}" || \
        ! grep -Eq '^common --override_module=go_dcgm=[^[:space:]]+$' "${bazel_local_config}"
}; then
    echo "ERROR: refusing to overwrite existing ${bazel_local_config}" >&2
    echo "Delete it or add the go_dcgm override manually, then rerun this command." >&2
    exit 1
fi

needs_go_override=true
if [[ -f "${go_workfile}" ]]; then
    if existing_result="$(GOWORK="${go_workfile}" "${go_command}" list -m -f '{{if or .Main .Replace}}{{.Dir}}{{end}}' "${go_dcgm_module}" 2>&1)"; then
        existing_dir="${existing_result}"
    else
        case "${existing_result}" in
            *"module ${go_dcgm_module}: not a known dependency") existing_dir="" ;;
            *) printf '%s\n' "${existing_result}" >&2; exit 1 ;;
        esac
    fi
    if [[ -n "${existing_dir}" ]]; then
        existing_source_dir="$(cd "${existing_dir}" && pwd -P)"
        if [[ "${existing_source_dir}" != "${source_dir}" ]]; then
            echo "ERROR: ${go_workfile} already uses go-dcgm at ${existing_dir}" >&2
            echo "Remove the matching replacement once, then rerun this command." >&2
            exit 1
        fi
        needs_go_override=false
    fi
else
    GOWORK=off "${go_command}" work init .
fi

if [[ "${needs_go_override}" == true ]]; then
    GOWORK=off "${go_command}" work edit \
        -use=. \
        -replace="${go_dcgm_module}=${source_dir}" \
        "${go_workfile}"
fi
resolved_dir="$(GOWORK="${go_workfile}" "${go_command}" list -m -f '{{.Dir}}' "${go_dcgm_module}")"
temporary_config="${bazel_local_config}.tmp"
printf '%s\n' \
    "${generated_config_header}" \
    "common --override_module=go_dcgm=${source_dir}" \
    >"${temporary_config}"
mv "${temporary_config}" "${bazel_local_config}"
echo "Go and Bazel now use ${go_dcgm_module} from ${resolved_dir}"

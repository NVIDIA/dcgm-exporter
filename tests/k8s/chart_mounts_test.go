package k8s

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"net/http"
	"time"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	corev1 "k8s.io/api/core/v1"
)

const (
	// chartMetricsFile is the metrics list inside chartMetricsDirectory, which
	// the chart's default config names.
	chartMetricsFile = chartMetricsDirectory + "/default-counters.csv"
	// metricsReloadTimeout covers the kubelet's ConfigMap volume sync, about a
	// minute by default, plus the exporter's reload.
	metricsReloadTimeout = 3 * time.Minute
	// reloadedHelp is the help text of the edited customMetrics list.
	reloadedHelp = "GPU temperature from the edited customMetrics list."
)

var _ = Describe("dcgm-exporter chart mount scenarios", func() {
	Context("DCGM exporter reads the files the chart mounts as directories", Ordered, Label("defaultChartMounts"), func() {
		AfterAll(func(ctx context.Context) {
			cleanupTestContext(ctx, kubeClient, helmClient)
		})

		It("should serve metrics with the chart defaults and no subPath mount", func(ctx context.Context) {
			exporterPod, _ := shouldInstallExporterAndReadMetrics(ctx,
				noArgumentsHelmValues(), nil, nil, baselineWithoutWorkload)
			Expect(chartMountsPodError(exporterPod)).To(Succeed())
			shouldLogMountedMetricsFile(ctx, exporterPod)
		})

		It("should serve metrics with a read-only root filesystem", func(ctx context.Context) {
			cleanupTestContext(ctx, kubeClient, helmClient)
			exporterPod, _ := shouldInstallExporterAndReadMetrics(ctx,
				append(noArgumentsHelmValues(), "securityContext.readOnlyRootFilesystem=true"), nil, nil, baselineWithoutWorkload)
			Expect(readOnlyRootFilesystemError(exporterPod)).To(Succeed())
			Expect(chartMountsPodError(exporterPod)).To(Succeed())
		})

		It("should serve metrics over HTTPS with TLS on", func(ctx context.Context) {
			cleanupTestContext(ctx, kubeClient, helmClient)
			shouldInstallHelmChart(ctx, helmClient,
				append(noArgumentsHelmValues(), "tlsServerConfig.enabled=true", "tlsServerConfig.autoGenerated=true"))
			exporterPod := shouldFindExporterPod(ctx, kubeClient, dcgmExporterPodLabels)
			shouldCheckIfPodIsReady(ctx, kubeClient, exporterPod.Namespace, exporterPod.Name)
			Expect(chartMountsPodError(exporterPod)).To(Succeed())

			status, body := shouldHTTPRequestPodPort(ctx, exporterPod, false, "", "")
			Expect(status).To(Equal(http.StatusBadRequest))
			Expect(string(body)).To(ContainSubstring("Client sent an HTTP request to an HTTPS server"))

			shouldEventuallyMeetBaselineMetricContract(func(g Gomega) []byte {
				status, body, err := requestPodPortPath(ctx, exporterPod, true, "", "", "metrics")
				g.Expect(err).NotTo(HaveOccurred())
				g.Expect(status).To(Equal(http.StatusOK))
				return body
			}, false)
		})

		It("should reload an edited customMetrics list in the running pod", func(ctx context.Context) {
			cleanupTestContext(ctx, kubeClient, helmClient)
			releaseName := shouldInstallHelmChart(ctx, helmClient, noArgumentsHelmValues())
			exporterPod := shouldFindExporterPod(ctx, kubeClient, dcgmExporterPodLabels)
			shouldCheckIfPodIsReady(ctx, kubeClient, exporterPod.Namespace, exporterPod.Name)
			shouldEventuallyReadMetrics(ctx, exporterPod, func(metrics []byte) error {
				return metricsHaveFamilyName(metrics, "DCGM_FI_DEV_FB_USED_BYTES")
			}, 2*time.Minute)

			shouldUpgradeHelmChart(ctx, helmClient, releaseName, noArgumentsHelmValues(),
				[]string{customMetricsJSONValue("DCGM_FI_DEV_GPU_TEMP_CELSIUS, gauge, " + reloadedHelp)})

			shouldEventuallyReadMetrics(ctx, exporterPod, func(metrics []byte) error {
				missing, err := missingMetricFamilies(metrics, []string{"DCGM_FI_DEV_FB_USED_BYTES"})
				if err != nil {
					return err
				}

				var stillThere error
				if len(missing) == 0 {
					stillThere = errors.New("DCGM_FI_DEV_FB_USED_BYTES is still exported after customMetrics dropped it")
				}

				// The help text differs from the default list's, so only the new file serves it.
				var notNew error
				if !bytes.Contains(metrics, []byte("# HELP DCGM_FI_DEV_GPU_TEMP_CELSIUS "+reloadedHelp)) {
					notNew = errors.New("DCGM_FI_DEV_GPU_TEMP_CELSIUS does not carry the help text of the edited customMetrics")
				}

				return errors.Join(stillThere, notNew)
			}, metricsReloadTimeout)
			shouldNotHaveRestarted(ctx, exporterPod)
		})
	})
})

// noArgumentsHelmValues returns Helm values that clear the suite's default
// exporter arguments (arguments={}), so the chart's own config decides which
// metrics file the exporter reads.
func noArgumentsHelmValues() []string {
	return []string{"arguments={}"}
}

// baselineWithoutWorkload checks the baseline metric contract for an exporter
// with no workload pod, so no Kubernetes labels are required.
func baselineWithoutWorkload(metrics []byte) error {
	return baselineMetricContractError(metrics, false)
}

// shouldEventuallyReadMetrics scrapes pod until check accepts the response or
// timeout passes. A failed scrape is retried, so a short proxy error does not
// fail the step.
func shouldEventuallyReadMetrics(ctx context.Context, pod *corev1.Pod, check func([]byte) error, timeout time.Duration) {
	Eventually(func(g Gomega) {
		metrics, err := kubeClient.DoHTTPRequest(ctx, testContext.namespace, pod.Name, dcgmExporterPort, "metrics")
		g.Expect(err).NotTo(HaveOccurred())
		g.Expect(check(metrics)).To(Succeed())
	}).WithPolling(5 * time.Second).Within(timeout).Should(Succeed())
}

// shouldLogMountedMetricsFile checks that the exporter logs that it uses the
// chart's mounted metrics list, so it reads that file and not the one the
// image ships.
func shouldLogMountedMetricsFile(ctx context.Context, pod *corev1.Pod) {
	Eventually(func(ctx context.Context) (string, error) {
		return kubeClient.GetPodLogs(ctx, pod.Namespace, pod.Name, exporterContainerName, nil)
	}).WithPolling(pollingIntervalNormal).Within(time.Minute).WithContext(ctx).
		Should(ContainSubstring(fmt.Sprintf("Using metric file '%s'", chartMetricsFile)))
}

// shouldNotHaveRestarted fails when the exporter pod was replaced or its
// container restarted, which would mean the change was not reloaded in place.
func shouldNotHaveRestarted(ctx context.Context, pod *corev1.Pod) {
	current, err := kubeClient.GetPod(ctx, pod.Namespace, pod.Name)
	Expect(err).NotTo(HaveOccurred())
	Expect(current.UID).To(Equal(pod.UID))

	for _, status := range current.Status.ContainerStatuses {
		Expect(status.RestartCount).To(BeZero(), "container %s restarted", status.Name)
	}
}

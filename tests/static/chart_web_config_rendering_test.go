const (
	webConfigKey          = "web-config.yaml"
	webConfigResourceName = "dcgm-exporter-web-config"
	webConfigVolumeName   = "web-config-yaml"
)

// exporterWebConfig captures the exporter-toolkit fields generated by the chart.
type exporterWebConfig struct {
	TLSServerConfig *struct {
		CertFile       string `json:"cert_file"`
		KeyFile        string `json:"key_file"`
		ClientAuthType string `json:"client_auth_type"`
		ClientCAFile   string `json:"client_ca_file"`
	} `json:"tls_server_config"`
	BasicAuthUsers map[string]string `json:"basic_auth_users"`
}

// decodeWebConfig parses the web configuration stored in a Secret.
func decodeWebConfig(t *testing.T, secret chartResource) exporterWebConfig {
	t.Helper()

	content, ok := secret.StringData[webConfigKey]
	require.True(t, ok, "Secret %q must contain %q", secret.Metadata.Name, webConfigKey)

	var config exporterWebConfig
	require.NoError(t, yaml.Unmarshal([]byte(content), &config))
	return config
}

// requireWebConfigMount checks the Secret volume, its directory mount, and that the exporter config points at the file in it.
func requireWebConfigMount(t *testing.T, resources []chartResource) {
	t.Helper()

	daemonSet := requireResourceKind(t, resources, "DaemonSet")
	secretVolume := requireVolume(t, daemonSet, webConfigVolumeName).Secret
	assert.Equal(t, webConfigResourceName, secretVolume.SecretName)
	assert.Equal(t, 0o664, secretVolume.DefaultMode)

	container := requireContainer(t, daemonSet, "exporter")
	mount := requireVolumeMount(t, container, webConfigVolumeName)
	assert.Equal(t, webConfigDirectory, mount.MountPath)
	assert.Empty(t, mount.SubPath)
	assert.Equal(t, webConfigPath, nestedValue(renderedConfig(t, resources), "server", "web_config_file"))
}

// TestChartWebConfigIsAbsentByDefault checks that disabled endpoint protection creates no web-config resource or mount.
func TestChartWebConfigIsAbsentByDefault(t *testing.T) {
	resources := renderChart(t, nil)
	assert.False(t, hasResourceName(resources, "Secret", webConfigResourceName))
	assert.False(t, hasResourceName(resources, "ConfigMap", webConfigResourceName))

	daemonSet := requireResourceKind(t, resources, "DaemonSet")
	assert.NotContains(t, daemonSetVolumeNames(daemonSet), webConfigVolumeName)

	container := requireContainer(t, daemonSet, "exporter")
	assert.NotContains(t, containerVolumeMountNames(container), webConfigVolumeName)
}

// TestChartWebConfigUsesASecret checks every supported TLS and basic-auth combination.
func TestChartWebConfigUsesASecret(t *testing.T) {
	const password = "chart-test-password"
	testCases := []struct {
		name           string
		values         map[string]interface{}
		wantTLS        bool
		wantClientAuth bool
		wantBasicAuth  bool
	}{
		{
			name: "basic auth only",
			values: map[string]interface{}{
				"basicAuth": map[string]interface{}{"users": map[string]interface{}{"admin": password}},
			},
			wantBasicAuth: true,
		},
		{
			name: "TLS only",
			values: map[string]interface{}{
				"tlsServerConfig": map[string]interface{}{"enabled": true},
			},
			wantTLS: true,
		},
		{
			name: "TLS with client auth",
			values: map[string]interface{}{
				"tlsServerConfig": map[string]interface{}{
					"enabled":        true,
					"clientAuthType": "RequireAndVerifyClientCert",
				},
			},
			wantTLS:        true,
			wantClientAuth: true,
		},
		{
			name: "TLS and basic auth",
			values: map[string]interface{}{
				"tlsServerConfig": map[string]interface{}{"enabled": true},
				"basicAuth":       map[string]interface{}{"users": map[string]interface{}{"admin": password}},
			},
			wantTLS:       true,
			wantBasicAuth: true,
		},
		{
			name: "TLS with client auth and basic auth",
			values: map[string]interface{}{
				"tlsServerConfig": map[string]interface{}{
					"enabled":        true,
					"clientAuthType": "RequireAndVerifyClientCert",
				},
				"basicAuth": map[string]interface{}{"users": map[string]interface{}{"admin": password}},
			},
			wantTLS:        true,
			wantClientAuth: true,
			wantBasicAuth:  true,
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			release, err := runHelmInstall(t, tc.values)
			require.NoError(t, err)
			resources := parseManifest(t, release.Manifest)

			secret := requireResourceName(t, resources, "Secret", webConfigResourceName)
			assert.Equal(t, "Opaque", secret.Type)
			assert.Len(t, secret.StringData, 1)
			assert.False(t, hasResourceName(resources, "ConfigMap", webConfigResourceName))
			requireWebConfigMount(t, resources)

			config := decodeWebConfig(t, secret)
			if tc.wantTLS {
				require.NotNil(t, config.TLSServerConfig)
				assert.Equal(t, "/etc/dcgm-exporter/tls/tls.crt", config.TLSServerConfig.CertFile)
				assert.Equal(t, "/etc/dcgm-exporter/tls/tls.key", config.TLSServerConfig.KeyFile)
				if tc.wantClientAuth {
					assert.Equal(t, "RequireAndVerifyClientCert", config.TLSServerConfig.ClientAuthType)
					assert.Equal(t, "/etc/dcgm-exporter/tls/ca.crt", config.TLSServerConfig.ClientCAFile)
				} else {
					assert.Empty(t, config.TLSServerConfig.ClientAuthType)
					assert.Empty(t, config.TLSServerConfig.ClientCAFile)
				}
			} else {
				assert.Nil(t, config.TLSServerConfig)
			}

			if tc.wantBasicAuth {
				hash := config.BasicAuthUsers["admin"]
				assert.Regexp(t, `^\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}$`, hash)
				assert.NotEqual(t, password, hash)
				assert.NotContains(t, release.Manifest, password)
			} else {
				assert.Empty(t, config.BasicAuthUsers)
			}
		})
	}
}

// With configMap.existingName and TLS on, the install notes name the path of
// the web config the chart mounts, which the user's config file or
// --web-config-file must name.
func TestChartExistingNameWebConfigNotes(t *testing.T) {
	release, err := runHelmInstall(t, map[string]interface{}{
		"configMap":       map[string]interface{}{"existingName": "mine"},
		"tlsServerConfig": map[string]interface{}{"enabled": true},
	})
	require.NoError(t, err)

	notes := strings.Join(strings.Fields(release.Info.Notes), " ")
	assert.Contains(t, notes, "Web config: the chart mounts it at "+webConfigPath+".")
}

// TestChartTLSExistingSecret checks that tlsServerConfig.existingSecret is
// mounted as the TLS volume, is expanded as a template, and stops the chart from
// creating its own TLS Secret.
func TestChartTLSExistingSecret(t *testing.T) {
	resources := renderChart(t, map[string]interface{}{
		"tlsServerConfig": map[string]interface{}{
			"enabled":        true,
			"existingSecret": "{{ .Release.Name }}-certs", // #nosec G101 -- a Secret name template, not a credential.
		},
	})

	volume := requireVolume(t, requireResourceKind(t, resources, "DaemonSet"), tlsVolumeName)
	assert.Equal(t, "dcgm-exporter-certs", volume.Secret.SecretName)

	for _, resource := range resources {
		assert.NotEqual(t, "dcgm-exporter-tls", resource.Metadata.Name, "the chart must not create its own TLS Secret")
	}

	// Without existingSecret the chart creates that Secret, so the loop above can fail.
	own := renderChart(t, map[string]interface{}{"tlsServerConfig": map[string]interface{}{"enabled": true}})
	requireResourceName(t, own, "Secret", "dcgm-exporter-tls")
}
